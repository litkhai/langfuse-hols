"""Five real `claude -p` runs (Claude Haiku) with the Stop hook from .run/settings.json.

Two throwaway git repositories under .run/repos/:
  allowed   origin https://github.com/lab/allowed-lab.git   (listed in .run/hook/repos.allow)
  denied    origin git@github.com:lab/denied-lab.git         (not listed)
Each holds config.env with secret-shaped fake values, generated here at random (.run/fakes.json),
so nothing secret-looking is committed. Every prompt asks Claude to read config.env, which puts
the values into a tool result, and carries one more fake value in the prompt itself.

Runs, as CC_LANGFUSE_CONTENT x repository:
  masked / allowed, prompts / allowed, none / allowed, full / allowed (the positive control),
  masked / denied
Results (session id, cost, usage, duration per run) go to .run/runs.json.
"""
import json
import os
import random
import string
import subprocess
import sys
import time
from pathlib import Path

LAB = Path(__file__).resolve().parent
RUN = LAB / ".run"
LOG = RUN / "state" / "langfuse_hook.log"
MODEL = "haiku"


def rnd(alphabet: str, n: int) -> str:
    return "".join(random.choice(alphabet) for _ in range(n))


def fakes() -> dict:
    up, low, dig = string.ascii_uppercase, string.ascii_lowercase, string.digits
    return {
        "aws_key_id": "AKIA" + rnd(up + dig, 16),
        "aws_secret": rnd(up + low + dig + "/+", 40),
        "db_password": "Lab" + rnd(low + dig, 12),
        "url_password": "pw" + rnd(low + dig, 10),
        "lf_secret": "sk-lf-" + "-".join(rnd("0123456789abcdef", n) for n in (8, 4, 4, 4, 12)),
        "prompt_password": "Pr" + rnd(low + dig, 12),
    }


def repo(name: str, origin: str, f: dict) -> Path:
    d = RUN / "repos" / name
    d.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q", str(d)], check=True)
    subprocess.run(["git", "-C", str(d), "remote", "remove", "origin"], capture_output=True)
    subprocess.run(["git", "-C", str(d), "remote", "add", "origin", origin], check=True)
    (d / "config.env").write_text(
        "# lab fixture, fake values generated by 03-runs.py\n"
        f"AWS_ACCESS_KEY_ID={f['aws_key_id']}\n"
        f"AWS_SECRET_ACCESS_KEY={f['aws_secret']}\n"
        f"CLICKHOUSE_PASSWORD={f['db_password']}\n"
        f"DATABASE_URL=postgres://app:{f['url_password']}@db:5432/app\n"
        f"LANGFUSE_SECRET_KEY={f['lf_secret']}\n"
        "LOG_LEVEL=info\n"
    )
    return d


def lines_done() -> int:
    return sum("Processed" in l for l in LOG.read_text().splitlines()) if LOG.exists() else 0


def main() -> int:
    if not (RUN / "settings.json").exists():
        sys.exit("run 02-install-hook.sh first")
    f = fakes()
    (RUN / "fakes.json").write_text(json.dumps(f, indent=1))
    os.chmod(RUN / "fakes.json", 0o600)
    repos = {
        "allowed": repo("allowed", "https://github.com/lab/allowed-lab.git", f),
        "denied": repo("denied", "git@github.com:lab/denied-lab.git", f),
    }
    plan = [("masked", "allowed"), ("prompts", "allowed"), ("none", "allowed"), ("full", "allowed"), ("masked", "denied")]
    prompt = ("Read config.env and answer with the number of lines only. "
              f"Ticket note, ignore it: DB_PASSWORD={f['prompt_password']}")
    before = lines_done()
    runs = []
    for mode, where in plan:
        env = dict(os.environ, CC_LANGFUSE_CONTENT=mode, CC_LANGFUSE_ENV_FILE=str(RUN / "langfuse.env"))
        t0 = time.time()
        p = subprocess.run(
            ["claude", "-p", "--model", MODEL, "--settings", str(RUN / "settings.json"),
             "--allowedTools", "Read", "--output-format", "json", prompt],
            cwd=repos[where], env=env, capture_output=True, text=True, timeout=300,
        )
        if p.returncode != 0:
            print(p.stderr[-2000:], file=sys.stderr)
            return 1
        out = json.loads(p.stdout)
        runs.append({"mode": mode, "repo": where, "session_id": out.get("session_id"),
                     "result": out.get("result"), "cost_usd": out.get("total_cost_usd"),
                     "duration_ms": out.get("duration_ms"), "num_turns": out.get("num_turns"),
                     "usage": out.get("usage"), "wall_s": round(time.time() - t0, 1)})
        print(f"  {mode:8} {where:8} session {str(out.get('session_id'))[:8]}  answer {str(out.get('result')).strip()[:20]!r}"
              f"  {out.get('total_cost_usd')} USD")
    # The hook uploads in the background after each run; wait for the four allowed runs.
    for _ in range(60):
        if lines_done() - before >= 4:
            break
        time.sleep(1)
    print(f"  hook log: {lines_done() - before} uploads finished (4 expected)")
    (RUN / "runs.json").write_text(json.dumps(runs, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
