def bench_texts(seed: int = 7):
    """Return [(text, intent_key)], shuffled, about 108,000 distinct sentences."""
    out = []
    for key, _label, wordings, _answers, _fail in INTENTS:
        for w in wordings:
            for o in OPENINGS:
                for c in CONTEXTS:
                    for cl in CLOSINGS:
                        out.append((f"{o}{c}{w}{cl}", key))
    seen, uniq = set(), []
    for t, k in out:
        if t not in seen:
            seen.add(t)
            uniq.append((t, k))
    random.Random(seed).shuffle(uniq)
    return uniq
